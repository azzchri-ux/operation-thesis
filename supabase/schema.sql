-- Esegui questo SQL in Supabase > SQL Editor.
create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(nickname) between 2 and 18),
  score integer not null check (score between 0 and 100 and score % 10 = 0),
  elapsed_seconds integer not null check (elapsed_seconds between 1 and 7200),
  created_at timestamptz not null default now()
);

alter table public.scores enable row level security;

-- Concedi solo le operazioni necessarie al ruolo pubblico anon.
grant select, insert on public.scores to anon;
grant usage, select on sequence public.scores_id_seq to anon;

-- Chiunque può leggere la classifica.
create policy "Public can read scores"
on public.scores for select
to anon
using (true);

-- Per la prima versione, chiunque può inviare un risultato.
-- NOTA: questa policy è adatta a uno scherzo tra amici, non a un concorso con premi.
create policy "Public can submit scores"
on public.scores for insert
to anon
with check (
  char_length(nickname) between 2 and 18
  and score between 0 and 100
  and score % 10 = 0
  and elapsed_seconds between 1 and 7200
);
